// Copies the AD ROAST rubric from the vault into api/_lib/rubric.ts.
// Run after editing the rubric in the vault:
//   node scripts/sync-roast-rubric.mjs "~/Desktop/Second Brain/02 Projects/Lead Magnets/AD ROAST/AD ROAST Rubric.md"
import { readFileSync, writeFileSync } from "node:fs";
import os from "node:os";

const src = (process.argv[2] || "").replace(/^~/, os.homedir());
if (!src) throw new Error("Pass the path to AD ROAST Rubric.md");
const md = readFileSync(src, "utf8").replace(/^---\n[\s\S]*?\n---\n+/, "").trim();
if (md.includes("`") || md.includes("${")) throw new Error("Rubric has a backtick or ${, escape it first");
writeFileSync(
  new URL("../api/_lib/rubric.ts", import.meta.url),
  `// Generated by scripts/sync-roast-rubric.mjs from the vault's "AD ROAST Rubric.md". Edit the vault file, then re-run.\nexport const RUBRIC = \`${md}\n\`;\n`,
);
console.log("rubric.ts written,", md.length, "chars");
